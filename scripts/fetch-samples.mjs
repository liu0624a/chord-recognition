// One-time utility: download a small set of per-note samples for each instrument
// from the midi-js-soundfonts CDN (FluidR3 GM soundfont, MIT licensed) into
// public/samples/, and emit src/audio/sampleManifest.ts to match.
//
// Run with:  node scripts/fetch-samples.mjs
// Re-run is safe: existing files are kept; the manifest is regenerated.

import { mkdir, writeFile, stat } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const BASE = 'https://gleitz.github.io/midi-js-soundfonts/FluidR3_GM';

// Each instrument is a GM instrument (FluidR3), a semitone "shift" applied to the
// samples (12 = the sample sounds an octave above its recorded pitch — used to
// approximate a ukulele from brighter nylon-guitar plucks), and the MIDI range of
// *recorded* pitches to fetch.
const INSTRUMENTS = {
  piano: { src: 'acoustic_grand_piano', shift: 0, from: 21, to: 108 },
  guitar: { src: 'acoustic_guitar_nylon', shift: 0, from: 40, to: 88 },
  ukulele: { src: 'acoustic_guitar_nylon', shift: 12, from: 45, to: 75 },
};
const STEP = 3;

const FLAT = ['C', 'Db', 'D', 'Eb', 'E', 'F', 'Gb', 'G', 'Ab', 'A', 'Bb', 'B'];

function noteName(midi) {
  const pc = ((midi % 12) + 12) % 12;
  const octave = Math.floor(midi / 12) - 1;
  return `${FLAT[pc]}${octave}`;
}

async function fetchOne(url, out) {
  try {
    const st = await stat(out);
    if (st.size > 0) return; // already downloaded
  } catch {
    /* not present yet */
  }
  const res = await fetch(url);
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  const buf = Buffer.from(await res.arrayBuffer());
  await mkdir(dirname(out), { recursive: true });
  await writeFile(out, buf);
}

async function main() {
  const manifest = {};
  for (const [key, cfg] of Object.entries(INSTRUMENTS)) {
    const samples = [];
    for (let midi = cfg.from; midi <= cfg.to; midi += STEP) {
      const name = noteName(midi);
      const url = `${BASE}/${cfg.src}-mp3/${name}.mp3`;
      const out = join(ROOT, 'public', 'samples', key, `${name}.mp3`);
      await fetchOne(url, out);
      samples.push({ file: `/samples/${key}/${name}.mp3`, midi });
      process.stdout.write(`  ${key}: ${name} (${midi})\n`);
    }
    manifest[key] = { shift: cfg.shift, samples };
  }

  const lines = [
    '// Sample sets for the Web Audio sampler. Generated by scripts/fetch-samples.mjs',
    '// from the FluidR3 GM soundfont (MIT licensed) — do not hand-edit the lists.',
    '// `midi` is the *recorded* pitch of each file; `shift` (semitones) tells the',
    "// sampler how far above that pitch the instrument's sound actually lives.",
    '',
    "import type { Instrument } from './synth';",
    '',
    'export interface InstrumentSample {',
    '  file: string;',
    '  midi: number;',
    '}',
    '',
    'export interface SampleSet {',
    '  shift: number;',
    '  samples: InstrumentSample[];',
    '}',
    '',
    'export const SAMPLE_SETS: Record<Instrument, SampleSet> = ' +
      JSON.stringify(manifest, null, 2) +
      ';',
    '',
  ];

  await writeFile(join(ROOT, 'src', 'audio', 'sampleManifest.ts'), lines.join('\n'));
  console.log('Wrote src/audio/sampleManifest.ts');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
